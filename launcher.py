def validate_agent_available(profile: AgentProfile) -> bool:
    return shutil.which(profile.command[0]) is not None


def _build_combined_context(
    profile: AgentProfile, root: Path, present_files: list[str]
) -> str:
    sections = [
        f"# Active Runtime Context for {profile.display_name}",
        "# Auto-generated by launcher.py — Follow ALL rules below.\n",
    ]
    for rel in present_files:
        body = (root / rel).read_text(encoding="utf-8")
        sections.append(f"\n---\n## Source: `{rel}`\n\n{body}")
    return "\n".join(sections)


def prepare_context_injection(profile: AgentProfile, project_root: Path) -> dict[str, Any]:
    root = project_root.resolve()
    present_files = [rel for rel in profile.context_files if (root / rel).is_file()]
    missing_files = [rel for rel in profile.context_files if rel not in present_files]

    if profile.name == "opencode":
        oc_cfg = {"$schema": "https://opencode.ai/config.json", "instructions": present_files}
        target_path = root / "opencode.json"
        target_path.write_text(json.dumps(oc_cfg, indent=2) + "\n", encoding="utf-8")
    elif profile.name == "claude":
        target_path = root / "CLAUDE.md"
    elif profile.name == "qwen":
        target_path = root / ".qwen_context.md"
        target_path.write_text(
            _build_combined_context(profile, root, present_files), encoding="utf-8"
        )
    elif profile.name == "agy":
        target_path = root / ".agy_context.md"
        target_path.write_text(
            _build_combined_context(profile, root, present_files), encoding="utf-8"
        )
    else:
        target_path = root / ".agent_runtime_context.md"
        target_path.write_text(
            _build_combined_context(profile, root, present_files), encoding="utf-8"
        )

    return {
        "agent": profile.name,
        "present_files": present_files,
        "missing_files": missing_files,
        "injected_context_path": str(target_path),
    }


def prepare_filtered_env(
    profile: AgentProfile,
    project_root: Path,
    ctx_info: dict[str, Any],
    *,
    source_env: dict[str, str] | None = None,
) -> dict[str, str]:
    src = dict(os.environ) if source_env is None else source_env
    filtered: dict[str, str] = {}

    for k in BASE_OS_ENV_KEYS:
        if k in src:
            filtered[k] = src[k]

    for k in profile.env_keys:
        if k in SAFE_API_ENV_KEYS and k in src:
            filtered[k] = src[k]

    metadata_file = project_root.resolve() / ".workforce_runtime.json"
    metadata = {
        "agent": profile.name,
        "context_file": ctx_info["injected_context_path"],
        "present_rules": ctx_info["present_files"],
    }
    metadata_file.write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    try:
        os.chmod(metadata_file, 0o600)
    except OSError:
        pass

    filtered["WORKFORCE_METADATA_FILE"] = str(metadata_file)
    return filtered


def launch_agent(profile: AgentProfile, project_root: Path, *, dry_run: bool = False) -> int:
    root = project_root.resolve()
    load_dotenv_file(root / ".env")
    ctx_info = prepare_context_injection(profile, root)

    if not dry_run and not validate_agent_available(profile):
        print(f"[X] '{profile.command[0]}' CLI ကို system ထဲမှာ မတွေ့ပါ။")
        print(f"    Install လုပ်ရန်: {profile.install_hint}")
        return 1

    env = prepare_filtered_env(profile, root, ctx_info)
    configured = [k for k in profile.env_keys if k in env]

    print(f"\n>>> [{profile.display_name}] ကို စတင်ဖွင့်လှစ်နေပါပြီ...")
    print(f"    Working Dir   : {root}")
    print(f"    Injected File : {ctx_info['injected_context_path']}")
    print(f"    Active API Env: {len(configured)}/{len(profile.env_keys)} configured (filtered)")

    if dry_run:
        print(f"    [DRY-RUN] Command: {' '.join(profile.command)}")
        return 0

    try:
        proc = subprocess.run(list(profile.command), cwd=root, env=env, check=False)
        return proc.returncode
    except KeyboardInterrupt:
        print("\n[!] User interrupted. Exiting gracefully.")
        return 130
